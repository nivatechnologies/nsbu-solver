//! Published SHA-256 known-answer input shared by artifact integrity and container tests.
use nsbu_solver::{
    checkpoint::artifacts::{Artifact, Kind},
    lineage::Digest,
};
// Published SHA-256 known-answer vector for the three ASCII bytes "abc".
pub const ABC: [u8; 32] = [
    0xba, 0x78, 0x16, 0xbf, 0x8f, 0x01, 0xcf, 0xea, 0x41, 0x41, 0x40, 0xde, 0x5d, 0xae, 0x22, 0x23,
    0xb0, 0x03, 0x61, 0xa3, 0x96, 0x17, 0x7a, 0x9c, 0xb4, 0x10, 0xff, 0x61, 0xf2, 0x00, 0x15, 0xad,
];
pub fn artifact(kind: Kind) -> Artifact<'static> {
    Artifact::verify(kind, Digest::new(ABC).unwrap(), b"abc", 3).unwrap()
}
